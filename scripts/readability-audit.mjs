import{dailyCatalog}from'./daily-catalog.mjs';
import vm from'node:vm';
import{readFileSync,mkdirSync,writeFileSync}from'node:fs';
import{createHash}from'node:crypto';
const c=vm.createContext({});
vm.runInContext(readFileSync(new URL('../learning-core.js',import.meta.url),'utf8'),c);
const L=c.CachasteLearning,{items}=dailyCatalog();
const digest=createHash('sha256').update(JSON.stringify(items.map(q=>[q.key,L.assessmentVersion(q)]))).digest('hex');
if(digest!=='d8a9b8965c4a53d288758624b89b00759b435664e9c6854d7051975be5e0b5fa')throw Error('Cambió una evaluación durante la pasada de lenguaje');
const report={scope:'Auditoría estructural y de redacción orientativa; NO certifica comprensión humana de 15 años ni validez conceptual.',assessmentDigest:digest,subjects:{},questions:items.length,flags:[],critical:0};
const flag=(q,kind,severity,detail)=>{report.flags.push({key:q.key,subject:q.subjectKey,kind,severity,detail});if(severity==='critical')report.critical++};
const words=s=>String(s||'').trim().split(/\s+/).filter(Boolean).length;
const generic=/^(?:recuerda el concepto|aplica la formula|lee con atencion|piensa bien|analiza la pregunta|revisa el contenido|usa la informacion dada)\.?$/i;
for(const q of items){
 const s=report.subjects[q.subjectKey]||={questions:0,shortOpenings:0,vocabularySupport:0,maxOpeningWords:0,flags:0};
 s.questions++;
 const opening=L.lessonOpening(q),count=words(opening.join(' '));
 s.shortOpenings+=count<=80?1:0;
 s.maxOpeningWords=Math.max(s.maxOpeningWords,count);
 s.vocabularySupport+=L.wordsFor(q).length?1:0;
 if(count>80)flag(q,'long_opening','critical','Apertura supera 80 palabras: '+count);
 if(!opening.length||!opening.some(p=>String(p).trim().length>=15))flag(q,'missing_opening','critical','No existe apertura educativa útil');
 const explanation=String(q.why||q.explanations?.[q.answer]||'').trim();
 if(explanation.length<30)flag(q,'brief_reasoning','review','Justificación principal de menos de 30 caracteres');
 const hint=String(q.hint||'').trim();
 if(hint&&generic.test(hint))flag(q,'generic_hint','review','Pista sin referencia específica al procedimiento');
 const opts=Array.from(q.options||[]);
 if(opts.length<4||!Number.isInteger(q.answer)||q.answer<0||q.answer>=opts.length)flag(q,'invalid_answer','critical','Alternativas o clave inválida');
 if(!String(q.question||q.q||'').trim())flag(q,'missing_question','critical','Enunciado vacío');
 if(q.explanations&&q.explanations.length!==opts.length)flag(q,'feedback_mismatch','critical','No hay explicación individual para cada alternativa');
 if(q.explanations&&q.explanations.some((x,i)=>i!==q.answer&&String(x||'').trim().length<12))flag(q,'thin_distractor_feedback','review','Justificación de distractor demasiado breve');
}
for(const flagItem of report.flags)report.subjects[flagItem.subject].flags++;
report.flagCount=report.flags.length;
mkdirSync(new URL('../reports/',import.meta.url),{recursive:true});
writeFileSync(new URL('../reports/readability-audit.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({questions:report.questions,subjects:report.subjects,flags:report.flagCount,critical:report.critical,digest}));
if(report.critical)throw Error(report.critical+' problemas estructurales críticos de presentación/explicación; revisar reports/readability-audit.json');
